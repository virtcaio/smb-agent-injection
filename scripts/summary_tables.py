"""Every number the write-up uses, as Markdown tables with 95% Wilson intervals.

  uv run python scripts/summary_tables.py [--armor 0.9.5] > results/SUMMARY.md
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import pandas as pd

R = Path("results")
MODELS = ["claude-haiku-5-5", "claude-sonnet-5-5", "claude-opus-5-5", "claude-sonnet-4-6", "claude-haiku-4-5"]
DEFENSES = ["none", "rule", "lock", "planlock", "armor", "monitor", "rule+lock", "rule+planlock", "rule+armor"]
ATTACKS = {"important_instructions": "classic", "owner_note": "owner's note"}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return max(0.0, c - h), min(1.0, c + h)


def pct(s: pd.Series) -> str:
    k, n = int(s.sum()), len(s)
    if n == 0:
        return "–"
    lo, hi = wilson(k, n)
    return f"{100 * k / n:.1f}% [{100 * lo:.1f}, {100 * hi:.1f}]"


def load(stages: list[str]) -> pd.DataFrame:
    frames = [pd.read_csv(R / s / "episodes.csv") for s in stages if (R / s / "episodes.csv").exists()]
    df = pd.concat(frames, ignore_index=True)
    for col in ("planlock_blocks", "armor_blocks", "lock_blocks", "monitor_blocks"):
        df[col] = df[col].fillna(0) if col in df else 0
    df["fired"] = (df.lock_blocks + df.planlock_blocks + df.monitor_blocks + df.armor_blocks) > 0
    return df


def table(rows: list[list[str]], header: list[str]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--armor", default="0.9.5")
    v = ap.parse_args().armor
    df = load(["full-benign", "full-attacked", f"armor-{v}-benign", f"armor-{v}-attacked",
               f"combo-{v}-benign", f"combo-{v}-attacked", "planlock-benign", "planlock-attacked"])
    benign, attacked = df[~df.attacked], df[df.attacked]
    out = [f"# Results\n\nGenerated by `scripts/summary_tables.py` (prompt-armor {v} for the `armor` rows). "
           f"{len(df):,} episodes. Brackets are 95% Wilson intervals.\n"]

    out.append("## 1. Attack success without any defense\n")
    rows = []
    for m in MODELS:
        g = attacked[(attacked.model == m) & (attacked.defense == "none")]
        rows.append([m] + [pct(g[g.attack == a].attack_success) for a in ATTACKS] + [str(len(g)), str(int(g.refused.sum()))])
    out.append(table(rows, ["model"] + [f"{n} attack" for n in ATTACKS.values()] + ["attacked episodes", "refusals"]))

    out.append("\n## 2. Utility without attack, and how often each defense fires on legitimate work\n")
    rows = []
    for m in MODELS:
        for d in DEFENSES:
            g = benign[(benign.model == m) & (benign.defense == d)]
            if len(g):
                rows.append([m, d, pct(g.utility), pct(g.fired) if d not in ("none", "rule") else "–", str(len(g))])
    out.append(table(rows, ["model", "defense", "utility", "episodes where the defense fired", "n"]))

    h = attacked[attacked.model == "claude-haiku-4-5"]
    out.append("\n## 3. Claude Haiku 4.5 under attack, by defense\n")
    rows = []
    for d in DEFENSES:
        g = h[h.defense == d]
        if len(g):
            rows.append([d] + [pct(g[g.attack == a].attack_success) for a in ATTACKS] + [pct(g.utility), str(len(g))])
    out.append(table(rows, ["defense"] + [f"attack success, {n}" for n in ATTACKS.values()] + ["utility under attack", "n"]))

    out.append("\n## 4. Claude Haiku 4.5 without defense, by language and by injection goal\n")
    g = h[h.defense == "none"]
    rows = [[ATTACKS[a]] + [pct(g[(g.attack == a) & (g.lang == lang)].attack_success) for lang in ("en", "pt")]
            + [pct(g[(g.attack == a) & (g.injection_kind == k)].attack_success) for k in ("marker", "exfil", "state")] for a in ATTACKS]
    out.append(table(rows, ["attack", "English", "Portuguese", "goal: marker", "goal: exfiltration", "goal: change state"]))
    rows = [[s, pct(g[g.suite == s].attack_success)] for s in ("marketplace", "inbox", "complaints", "newsletter")]
    out.append("\n" + table(rows, ["workflow", "attack success (both attacks)"]))

    out.append("\n## 5. The detector, version by version\n")
    rows = []
    for ver in ("0.9.3", v):
        off = R / f"detector-offline-{ver}" / "tool_outputs.csv"
        if not off.exists():
            continue
        o = pd.read_csv(off)
        o["blocked"] = o.decision == "block"
        b, a = o[~o.carries_attack], o[o.carries_attack]
        ep = b.groupby(["suite", "lang", "task_id"]).blocked.any().reset_index()
        ab = load([f"armor-{ver}-benign"])
        aa = load([f"armor-{ver}-attacked"])
        for lang in ("en", "pt"):
            rows.append([ver, lang, pct(b[b.lang == lang].blocked), pct(ep[ep.lang == lang].blocked), pct(a[a.lang == lang].blocked),
                         pct(ab[ab.lang == lang].fired), pct(ab[ab.lang == lang].utility),
                         pct(aa[(aa.lang == lang) & (aa.attack == "owner_note")].attack_success)])
    out.append(table(rows, ["prompt-armor", "language", "legitimate tool results blocked", "legitimate trajectories with a block",
                            "tool results carrying the attack blocked", "in the agent: legitimate episodes with a block (5 models)",
                            "in the agent: utility without attack (5 models)", "in the agent: Haiku 4.5 owner's-note attack success"]))
    out.append("\nThe first three columns run the detector alone over the tool results of the ground-truth trajectories "
               "(`scripts/detector_offline.py`); the rest come from the agent runs.")

    pc = R / "plan-check" / "pairs.csv"
    if pc.exists():
        p, t = pd.read_csv(pc), pd.read_csv(R / "plan-check" / "tasks.csv")
        need = t[t.needs_action]
        out.append("\n## 6. The realistic lock's planner on its own\n")
        out.append(table([[f"{int(t.error.notna().sum())} of {len(t)}", pct(need.covers), pct(need.planned.str.contains(r"'\*'")),
                           pct(p.passes_planlock), pct(p.passes_oracle)]],
                         ["planner errors", "tasks with every needed action allowed", "action tasks with an open target",
                          "attacker's action allowed, planned lock", "attacker's action allowed, oracle lock"]))

    out.append("\n## 7. Cost per episode without defense (US$, list prices, prompt caching on)\n")
    rows = [[m, f"{benign[(benign.model == m) & (benign.defense == 'none')][['cost_agent', 'cost_monitor']].sum(axis=1).mean():.4f}"] for m in MODELS]
    out.append(table(rows, ["model", "cost per episode"]))
    print("\n".join(out))


if __name__ == "__main__":
    main()
